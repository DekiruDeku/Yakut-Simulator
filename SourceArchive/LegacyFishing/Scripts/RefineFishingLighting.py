import unreal

AssetTools=unreal.AssetToolsHelpers.get_asset_tools()
Path='/Game/Fishing/Materials/M_MaritimeSky'
Material=unreal.load_asset(Path)
if not Material:
    Material=AssetTools.create_asset('M_MaritimeSky','/Game/Fishing/Materials',unreal.Material,unreal.MaterialFactoryNew())
unreal.MaterialEditingLibrary.delete_all_material_expressions(Material)
Material.set_editor_property('shading_model',unreal.MaterialShadingModel.MSM_UNLIT)
Material.set_editor_property('two_sided',True)
Material.set_editor_property('is_sky',True)
def Node(Class):
    return unreal.MaterialEditingLibrary.create_material_expression(Material,Class)
Direction=Node(unreal.MaterialExpressionCameraVectorWS)
Mask=Node(unreal.MaterialExpressionComponentMask)
Mask.set_editor_property('r',False)
Mask.set_editor_property('g',False)
Mask.set_editor_property('b',True)
unreal.MaterialEditingLibrary.connect_material_expressions(Direction,'',Mask,'None')
Negate=Node(unreal.MaterialExpressionMultiply)
Negate.set_editor_property('const_b',-1)
unreal.MaterialEditingLibrary.connect_material_expressions(Mask,'',Negate,'A')
Saturate=Node(unreal.MaterialExpressionSaturate)
unreal.MaterialEditingLibrary.connect_material_expressions(Negate,'',Saturate,'None')
Horizon=Node(unreal.MaterialExpressionConstant3Vector)
Horizon.set_editor_property('constant',unreal.LinearColor(.58,.72,.80,1))
Zenith=Node(unreal.MaterialExpressionConstant3Vector)
Zenith.set_editor_property('constant',unreal.LinearColor(.14,.32,.49,1))
Gradient=Node(unreal.MaterialExpressionLinearInterpolate)
unreal.MaterialEditingLibrary.connect_material_expressions(Horizon,'',Gradient,'A')
unreal.MaterialEditingLibrary.connect_material_expressions(Zenith,'',Gradient,'B')
unreal.MaterialEditingLibrary.connect_material_expressions(Saturate,'',Gradient,'Alpha')
Texture=Node(unreal.MaterialExpressionTextureSample)
Texture.set_editor_property('texture',unreal.load_asset('/Engine/EngineSky/T_Sky_Clouds_M'))
Coordinate=Node(unreal.MaterialExpressionTextureCoordinate)
Coordinate.set_editor_property('u_tiling',1.5)
Coordinate.set_editor_property('v_tiling',1)
unreal.MaterialEditingLibrary.connect_material_expressions(Coordinate,'',Texture,'UVs')
Clouds=Node(unreal.MaterialExpressionLinearInterpolate)
Clouds.set_editor_property('const_b',.82)
unreal.MaterialEditingLibrary.connect_material_expressions(Gradient,'',Clouds,'A')
unreal.MaterialEditingLibrary.connect_material_expressions(Texture,'R',Clouds,'Alpha')
Brightness=Node(unreal.MaterialExpressionMultiply)
Brightness.set_editor_property('const_b',1)
unreal.MaterialEditingLibrary.connect_material_expressions(Clouds,'',Brightness,'A')
unreal.MaterialEditingLibrary.connect_material_property(Brightness,'',unreal.MaterialProperty.MP_EMISSIVE_COLOR)
unreal.MaterialEditingLibrary.recompile_material(Material)
unreal.EditorAssetLibrary.save_loaded_asset(Material)
Actors=unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
SkyActors=[Actor for Actor in Actors.get_all_level_actors() if Actor.get_actor_label()=='MaritimeSkyDome']
if SkyActors:
    Sky,=SkyActors
else:
    Sky=Actors.spawn_actor_from_class(unreal.StaticMeshActor,unreal.Vector(0,0,0))
    Sky.set_actor_label('MaritimeSkyDome')
Sky.static_mesh_component.set_static_mesh(unreal.load_asset('/Engine/EngineSky/SM_SkySphere'))
Sky.static_mesh_component.set_material(0,Material)
Sky.static_mesh_component.set_collision_profile_name('NoCollision')
Sky.static_mesh_component.set_cast_shadow(False)
Sky.set_actor_scale3d(unreal.Vector(1000,1000,1000))
for Actor in Actors.get_all_level_actors():
    if isinstance(Actor,unreal.DirectionalLight):
        Actor.light_component.set_editor_property('intensity',4)
    if isinstance(Actor,unreal.PostProcessVolume):
        Settings=Actor.get_editor_property('settings')
        Settings.set_editor_property('camera_shutter_speed',60)
        Settings.set_editor_property('auto_exposure_apply_physical_camera_exposure',False)
        Actor.set_editor_property('settings',Settings)
    if isinstance(Actor,unreal.SkyLight):
        Actor.light_component.set_editor_property('intensity',.7)
        Actor.light_component.recapture_sky()
unreal.get_editor_subsystem(unreal.LevelEditorSubsystem).save_current_level()
unreal.EditorLevelLibrary.editor_set_game_view(True)
print('Maritime sky, exposure and ocean lighting saved')
